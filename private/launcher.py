#!/usr/bin/env python3
"""openmeter_server launcher: OpenMeter's API server and sink worker on
free 127.0.0.1 ports, against the backing services' env files.

  serve  wait for the Kafka, ClickHouse and Postgres env files; write
         config.yaml into the state dir; start `openmeter` (it migrates
         Postgres, creates the ClickHouse events table and the default
         namespace's Kafka topic, and loads the meters); wait for
         GET /api/v1/meters; start `openmeter-sink-worker`; wait until it
         is assigned the namespace's events topic partitions; write the env
         file; run until SIGTERM/SIGINT/SIGHUP.

Both processes run with a clean environment (OpenMeter's viper config
reads every environment variable as a config override), cwd/HOME/TMPDIR in
the state dir, in their own session, and (Linux) PR_SET_PDEATHSIG=SIGKILL,
so a SIGKILLed launcher leaves nothing behind. Their output (JSON logs) goes
to server.log and sink-worker.log in the state dir; tracing, metrics and
log exporters are off, so nothing is sent anywhere.
"""

import argparse
import ctypes
import json
import os
import re
import shlex
import signal
import socket
import subprocess
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

_TAIL = 25
_STOP_TIMEOUT = 20
_PORT_ATTEMPTS = 3

# The sink worker's Kafka consumer group (upstream's default, set explicitly).
SINK_GROUP = "openmeter-sink-worker"


def log(msg):
    print(f"[openmeter] {msg}", file=sys.stderr, flush=True)


class Fatal(Exception):
    pass


# ---- env files ----------------------------------------------------------------

def read_env(path):
    """KEY=VALUE lines, values shell-quoted (rules_kafka, rules_clickhouse)
    or bare (rules_pg)."""
    out = {}
    with open(path) as f:
        for line in f:
            line = line.rstrip("\n")
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            try:
                parts = shlex.split(v)
                v = parts[0] if len(parts) == 1 else ("" if not parts else v)
            except ValueError:
                pass
            out[k.strip()] = v
    return out


def wait_env_files(files, deadline, stopping):
    """files: {service: path}. Returns {service: {var: value}}."""
    missing = dict(files)
    noted = False
    while missing:
        for svc, path in list(missing.items()):
            if os.path.isfile(path):
                del missing[svc]
        if not missing:
            break
        if stopping():
            raise Fatal("stopped while waiting for the backing services")
        if time.monotonic() >= deadline:
            raise Fatal("timed out waiting for the backing services' env files: " +
                        ", ".join(f"{s} ({p})" for s, p in sorted(missing.items())) +
                        "; is each server running (rules_itest: in the openmeter service's deps)?")
        if not noted:
            log("waiting for " + ", ".join(f"{s} env file {p}" for s, p in sorted(missing.items())))
            noted = True
        time.sleep(0.1)
    return {svc: read_env(path) for svc, path in files.items()}


def need(env, svc, path, *names):
    for n in names:
        if n not in env:
            raise Fatal(f"{svc} env file {path} has no {n}")
    return [env[n] for n in names]


# ---- config -------------------------------------------------------------------

def free_ports(n):
    socks = []
    try:
        for _ in range(n):
            s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            s.bind(("127.0.0.1", 0))
            socks.append(s)
        return [s.getsockname()[1] for s in socks]
    finally:
        for s in socks:
            s.close()


def q(s):
    # A JSON string is a valid YAML double-quoted scalar.
    return json.dumps(str(s))


def duration_ms(text):
    m = re.fullmatch(r"(\d+(?:\.\d+)?)(ms|s|m)", text)
    if not m:
        raise Fatal(f"bad duration {text!r}")
    return float(m.group(1)) * {"ms": 1, "s": 1000, "m": 60000}[m.group(2)]


def render_config(a, api_port, server_tel_port, sink_tel_port, kafka, ch, pg):
    """The generated config.yaml (meters are appended after it). Every
    address is 127.0.0.1; every exporter is off."""
    pg_url = "postgres://{}:{}@{}:{}/{}?sslmode=disable".format(
        urllib.parse.quote(pg["PGUSER"], safe=""),
        urllib.parse.quote(pg["PGPASSWORD"], safe=""),
        pg["PGHOST"], pg["PGPORT"],
        urllib.parse.quote(pg["PGDATABASE"], safe=""),
    )
    flush_ms = duration_ms(a.flush_interval)
    poll = f"{int(min(100, max(10, flush_ms)))}ms"
    return f"""\
# Generated by rules_openmeter's openmeter_server ({a.name}); do not edit.
# Metering only: the API server and the sink worker. No Svix (no svix.apiKey:
# webhooks go to OpenMeter's no-op handler), no balance, billing or
# notification workers, no Redis (dedupe and the progress manager are off).
address: {q(f"127.0.0.1:{api_port}")}
environment: "test"

telemetry:
  address: {q(f"127.0.0.1:{server_tel_port}")}
  trace:
    sampler: never
    exporters:
      otlp:
        enabled: false
  metrics:
    exporters:
      prometheus:
        enabled: false
      otlp:
        enabled: false
  log:
    format: json
    level: {q(a.log_level)}
    exporters:
      otlp:
        enabled: false
      stdout:
        enabled: false
      file:
        enabled: false

termination:
  checkInterval: 1s
  gracefulShutdownTimeout: 10s
  propagationTimeout: 0s

namespace:
  default: {q(a.namespace)}

ingest:
  kafka:
    broker: {q(kafka["KAFKA_BOOTSTRAP_SERVERS"])}
    brokerAddressFamily: v4
    statsInterval: 0s
    socketKeepAliveEnabled: false
    partitions: 1

aggregation:
  clickhouse:
    address: {q(ch["CLICKHOUSE_NATIVE_ADDR"])}
    database: {q(ch["CLICKHOUSE_DATABASE"])}
    username: {q(ch["CLICKHOUSE_USER"])}
    password: {q(ch.get("CLICKHOUSE_PASSWORD", ""))}
    poolMetrics:
      enabled: false

dedupe:
  enabled: false

sink:
  minCommitCount: {a.min_commit_count}
  maxCommitWait: {q(a.flush_interval)}
  maxPollTimeout: {q(poll)}
  namespaceRefetch: 1s
  namespaceRefetchTimeout: 1s
  meterRefetchInterval: 1s
  dedupe:
    enabled: false
  kafka:
    brokers: {q(kafka["KAFKA_BOOTSTRAP_SERVERS"])}
    brokerAddressFamily: v4
    statsInterval: 0s
    # The group whose offsets the launcher sets to the start of the events
    # topic before the sink worker starts (see reset_offsets). OpenMeter
    # hardcodes auto.offset.reset=latest for the sink, whatever is set here.
    consumerGroupId: {q(SINK_GROUP)}

postgres:
  url: {q(pg_url)}
  autoMigrate: migration

events:
  enabled: false
portal:
  enabled: false
credits:
  enabled: false
progressManager:
  enabled: false
apps:
  baseURL: {q(f"http://127.0.0.1:{api_port}")}
"""


# ---- processes ----------------------------------------------------------------

def _pdeathsig():
    os.setsid()
    if sys.platform.startswith("linux"):
        try:
            ctypes.CDLL(None, use_errno=True).prctl(1, signal.SIGKILL)  # PR_SET_PDEATHSIG
        except (OSError, AttributeError):
            pass


def clean_env(state_dir):
    tmp = os.path.join(state_dir, "tmp")
    os.makedirs(tmp, exist_ok=True)
    return {"PATH": "/usr/bin:/bin", "HOME": state_dir, "TMPDIR": tmp, "LANG": "C.UTF-8"}


def spawn(cmd, state_dir, log_path):
    out = open(log_path, "ab")
    try:
        return subprocess.Popen(cmd, cwd=state_dir, env=clean_env(state_dir), stdin=subprocess.DEVNULL,
                                stdout=out, stderr=subprocess.STDOUT, preexec_fn=_pdeathsig)
    finally:
        out.close()


def stop(proc, timeout=_STOP_TIMEOUT):
    if proc is None or proc.poll() is not None:
        return
    try:
        os.kill(proc.pid, signal.SIGTERM)
    except ProcessLookupError:
        return
    try:
        proc.wait(timeout)
    except subprocess.TimeoutExpired:
        log(f"pid {proc.pid} still running after {timeout}s; SIGKILL")
    try:
        os.killpg(proc.pid, signal.SIGKILL)
    except (ProcessLookupError, PermissionError):
        pass
    proc.wait()


def tail(path, n=_TAIL):
    try:
        with open(path, errors="replace") as f:
            return f.read().splitlines()[-n:]
    except OSError:
        return []


def explain(path):
    """The errors in an OpenMeter log: `configuration error:` blocks,
    panics and ERROR-level JSON records (message + error), else the tail."""
    lines = tail(path, 400)
    picked = []
    for i, line in enumerate(lines):
        if line.startswith("configuration error") or line.startswith("panic:"):
            picked.extend(l for l in lines[i:i + 15] if not l.startswith("\t") and not l.startswith("goroutine"))
            break
        if line.startswith("{"):
            try:
                rec = json.loads(line)
            except ValueError:
                continue
            if str(rec.get("level", "")).upper() in ("ERROR", "FATAL"):
                msg = rec.get("msg", "")
                err = rec.get("error") or rec.get("err") or ""
                picked.append(f"{msg}: {err}" if err else msg)
    body = picked[-12:] if picked else lines[-_TAIL:]
    return "\n".join("  " + l for l in body)


def http_get(url, timeout=2):
    try:
        with urllib.request.urlopen(url, timeout=timeout) as r:
            return r.status, r.read()
    except urllib.error.HTTPError as e:
        return e.code, e.read()
    except (OSError, ValueError):
        return None, b""


def reset_offsets(kafka, topic, state_dir, deadline):
    """Commit offset 0 (the earliest) for the sink worker's consumer group on
    every partition of the events topic, before the sink worker starts.

    Why: OpenMeter's sink worker hardcodes auto.offset.reset=latest
    (app/common/openmeter_sinkworker.go: NewSinkKafkaConsumer), so a fresh
    group starts at the end of the topic. That end is looked up only after
    the partition is assigned (the "kafka partition assignment" record is
    logged before), so an event produced in that window, i.e. the first
    events a test sends the moment the stack is ready, is skipped for good.
    With a committed offset the consumer starts there and never consults
    auto.offset.reset. Uses rules_kafka's kafka_cli (one JVM, about a
    second); the group has no members yet, which --reset-offsets requires."""
    testlib = kafka.get("KAFKA_TESTLIB")
    if not testlib:
        raise Fatal("the kafka env file has no KAFKA_TESTLIB (rules_kafka >= 0.2.0 writes it)")
    env = {k: v for k, v in kafka.items()}
    env.update(clean_env(state_dir))
    env["TEST_TMPDIR"] = state_dir  # kafka_cli's logs and temp files
    script = ('source "$KAFKA_TESTLIB" && kafka_cli kafka-consumer-groups --bootstrap-server '
              '"$KAFKA_BOOTSTRAP_SERVERS" --group "$1" --topic "$2" --reset-offsets --to-earliest --execute')
    last = ""
    while True:
        r = subprocess.run(["bash", "-c", script, "reset_offsets", SINK_GROUP, topic], env=env, cwd=state_dir,
                           stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        last = r.stdout.strip()
        rows = [l.split() for l in last.splitlines()]
        parts = [f for f in rows if len(f) >= 4 and f[0] == SINK_GROUP and f[1] == topic]
        if r.returncode == 0 and parts and all(f[3] == "0" for f in parts):
            return len(parts)
        if time.monotonic() >= deadline:
            raise Fatal(f"could not set the sink worker's offsets on {topic}:\n" +
                        "\n".join("  " + l for l in last.splitlines()[-15:]))
        time.sleep(0.5)


def port_clash(path):
    return any("address already in use" in l for l in tail(path, 200))


def sink_assigned(path, topic):
    for line in tail(path, 2000):
        if "kafka partition assignment" in line and topic in line:
            return True
    return False


# ---- serve ----------------------------------------------------------------------

class Stack:
    def __init__(self, a):
        self.a = a
        self.server = None
        self.sink = None
        self.stopping = False
        self.state = a.state_dir
        self.server_log = os.path.join(self.state, "server.log")
        self.sink_log = os.path.join(self.state, "sink-worker.log")
        self.config = os.path.join(self.state, "config.yaml")

    def check_stop(self):
        if self.stopping:
            raise Fatal("stopped during start-up")

    def wait_until(self, what, ok, proc, log_path, deadline):
        while True:
            self.check_stop()
            if ok():
                return
            if proc.poll() is not None:
                return proc.returncode
            if time.monotonic() >= deadline:
                raise Fatal(f"{what} not ready within {self.a.ready_timeout}s; last lines of {log_path}:\n" +
                            "\n".join("  " + l for l in tail(log_path)))
            time.sleep(0.1)

    def start(self, envs, deadline):
        a = self.a
        topic = f"om_{a.namespace}_events"
        for attempt in range(1, _PORT_ATTEMPTS + 1):
            api, stel, ktel = free_ports(3)
            with open(self.config, "w") as f:
                f.write(render_config(a, api, stel, ktel, envs["kafka"], envs["clickhouse"], envs["postgres"]))
                if a.meters:
                    with open(a.meters) as m:
                        f.write("\n# ---- meters (from the meters attribute) ----\n")
                        f.write(m.read())
                        f.write("\n")
            url = f"http://127.0.0.1:{api}"
            t0 = time.monotonic()
            log(f"starting OpenMeter {a.version} API server on 127.0.0.1:{api} (attempt {attempt})")
            for p in (self.server_log, self.sink_log):
                open(p, "w").close()
            self.server = spawn([a.server, "--config", self.config], self.state, self.server_log)
            rc = self.wait_until("OpenMeter API server (GET /api/v1/meters)",
                                 lambda: http_get(url + "/api/v1/meters")[0] == 200,
                                 self.server, self.server_log, deadline)
            if rc is not None:
                if port_clash(self.server_log) and attempt < _PORT_ATTEMPTS:
                    log("port taken; retrying with new ports")
                    continue
                raise Fatal(f"the OpenMeter API server exited (status {rc}) before it was ready:\n" + explain(self.server_log))
            t_api = time.monotonic() - t0

            # The sink worker's telemetry address is the only thing it binds.
            sink_cfg = self.config
            with open(self.config) as f:
                text = f.read()
            sink_cfg = os.path.join(self.state, "sink-worker.yaml")
            with open(sink_cfg, "w") as f:
                f.write(text.replace(f'address: "127.0.0.1:{stel}"', f'address: "127.0.0.1:{ktel}"', 1))
            t1 = time.monotonic()
            n = reset_offsets(envs["kafka"], topic, self.state, deadline)
            t_offsets = time.monotonic() - t1
            log(f"sink worker group {SINK_GROUP}: offsets of {topic} ({n} partition{'s' if n > 1 else ''}) set to the earliest")
            log("starting the sink worker")
            self.sink = spawn([a.sink_worker, "--config", sink_cfg], self.state, self.sink_log)
            rc = self.wait_until(f"OpenMeter sink worker (assigned {topic})",
                                 lambda: sink_assigned(self.sink_log, topic)
                                 and http_get(f"http://127.0.0.1:{ktel}/healthz/ready")[0] == 200,
                                 self.sink, self.sink_log, deadline)
            if rc is not None:
                if port_clash(self.sink_log) and attempt < _PORT_ATTEMPTS:
                    log("port taken; retrying with new ports")
                    stop(self.server)
                    continue
                raise Fatal(f"the OpenMeter sink worker exited (status {rc}) before it was ready:\n" + explain(self.sink_log))
            t_sink = time.monotonic() - t1
            return dict(url=url, api_port=api, server_tel=stel, sink_tel=ktel, topic=topic, t_api=t_api, t_sink=t_sink,
                        t_offsets=t_offsets)
        raise Fatal("could not bind free ports")

    def stop_all(self):
        stop(self.sink)
        stop(self.server)


def write_env(env_file, values):
    """Atomically: a reader that sees the file sees all of it."""
    tmp = env_file + ".tmp"
    with open(tmp, "w") as f:
        for k, v in values.items():
            f.write(f"{k}={shlex.quote(str(v))}\n")
    os.replace(tmp, env_file)


def serve(a):
    t_start = time.monotonic()
    os.makedirs(a.state_dir, exist_ok=True)
    st = Stack(a)

    def on_signal(signum, _frame):
        st.stopping = True

    for s in (signal.SIGTERM, signal.SIGINT, signal.SIGHUP):
        signal.signal(s, on_signal)

    try:
        os.remove(a.env_file)
    except FileNotFoundError:
        pass

    deadline = time.monotonic() + a.ready_timeout
    files = {"kafka": a.kafka_env, "clickhouse": a.clickhouse_env, "postgres": a.postgres_env}
    try:
        envs = wait_env_files(files, deadline, lambda: st.stopping)
        need(envs["kafka"], "kafka", a.kafka_env, "KAFKA_BOOTSTRAP_SERVERS")
        need(envs["clickhouse"], "clickhouse", a.clickhouse_env,
             "CLICKHOUSE_NATIVE_ADDR", "CLICKHOUSE_DATABASE", "CLICKHOUSE_USER")
        need(envs["postgres"], "postgres", a.postgres_env, "PGHOST", "PGPORT", "PGDATABASE", "PGUSER", "PGPASSWORD")
        t_wait = time.monotonic() - t_start
        info = st.start(envs, deadline)
    except Fatal as e:
        st.stop_all()
        log(f"error: {e}")
        return 0 if st.stopping else 1

    ingest = info["url"] + "/api/v1/events"
    values = {
        "OPENMETER_URL": info["url"],
        "OPENMETER_INGEST_URL": ingest,
        "OPENMETER_NAMESPACE": a.namespace,
        "OPENMETER_HOST": "127.0.0.1",
        "OPENMETER_PORT": info["api_port"],
        "OPENMETER_EVENTS_TOPIC": info["topic"],
        "OPENMETER_VERSION": a.version,
        "OPENMETER_SINK_FLUSH_INTERVAL": a.flush_interval,
        "OPENMETER_SINK_MIN_COMMIT_COUNT": a.min_commit_count,
        "OPENMETER_TELEMETRY_URL": f"http://127.0.0.1:{info['server_tel']}",
        "OPENMETER_SINK_TELEMETRY_URL": f"http://127.0.0.1:{info['sink_tel']}",
        "OPENMETER_SERVER_PID": st.server.pid,
        "OPENMETER_SINK_PID": st.sink.pid,
        "OPENMETER_STATE_DIR": a.state_dir,
        "OPENMETER_CONFIG": st.config,
        "OPENMETER_SERVER_LOG": st.server_log,
        "OPENMETER_SINK_LOG": st.sink_log,
        "OPENMETER_BIN": a.server,
        "OPENMETER_SINK_WORKER_BIN": a.sink_worker,
        "OPENMETER_KAFKA_ENV": a.kafka_env,
        "OPENMETER_CLICKHOUSE_ENV": a.clickhouse_env,
        "OPENMETER_POSTGRES_ENV": a.postgres_env,
    }
    write_env(a.env_file, values)
    log(f"OpenMeter {a.version} ready at {info['url']} in {time.monotonic() - t_start:.1f}s "
        f"(backing services {t_wait:.1f}s, API server {info['t_api']:.1f}s, sink offsets {info['t_offsets']:.1f}s, "
        f"sink worker {info['t_sink'] - info['t_offsets']:.1f}s)")

    rc = 0
    while not st.stopping:
        for name, proc, path in (("API server", st.server, st.server_log), ("sink worker", st.sink, st.sink_log)):
            if proc.poll() is not None:
                log(f"the OpenMeter {name} exited (status {proc.returncode}):\n" + explain(path))
                rc = 1
                st.stopping = True
                break
        time.sleep(0.2)
    try:
        os.remove(a.env_file)
    except FileNotFoundError:
        pass
    st.stop_all()
    return rc


def main(argv):
    p = argparse.ArgumentParser(prog="openmeter_server")
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("serve")
    s.add_argument("--name", required=True)
    s.add_argument("--server", required=True)
    s.add_argument("--sink-worker", required=True)
    s.add_argument("--version", required=True)
    s.add_argument("--state-dir", required=True)
    s.add_argument("--env-file", required=True)
    s.add_argument("--kafka-env", required=True)
    s.add_argument("--clickhouse-env", required=True)
    s.add_argument("--postgres-env", required=True)
    s.add_argument("--meters", default="")
    s.add_argument("--namespace", default="default")
    s.add_argument("--flush-interval", default="250ms")
    s.add_argument("--min-commit-count", type=int, default=500)
    s.add_argument("--log-level", default="info")
    s.add_argument("--ready-timeout", type=float, default=180)
    a = p.parse_args(argv)
    return serve(a)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
